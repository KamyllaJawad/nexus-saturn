/** Junta a metade direita com a esquerda espelhada e devolve o `d` de um <path> fechado. */
export function caminhoSuave(metade: Ponto[]): string {
  const espelho = metade
    .slice(1, -1)
    .reverse()
    .map(([x, y]): Ponto => [200 - x, y])
  const p = [...metade, ...espelho]
  const n = p.length
  const f = (v: number) => v.toFixed(1)

  let d = `M${p[0]![0]} ${p[0]![1]}`
  for (let i = 0; i < n; i++) {
    const a = p[(i - 1 + n) % n]!
    const b = p[i]!
    const c = p[(i + 1) % n]!
    const e = p[(i + 2) % n]!
    const c1x = b[0] + (c[0] - a[0]) / 6
    const c1y = b[1] + (c[1] - a[1]) / 6
    const c2x = c[0] - (e[0] - b[0]) / 6
    const c2y = c[1] - (e[1] - b[1]) / 6
    d += `C${f(c1x)} ${f(c1y)} ${f(c2x)} ${f(c2y)} ${c[0]} ${c[1]}`
  }
  return d + 'Z'
}


